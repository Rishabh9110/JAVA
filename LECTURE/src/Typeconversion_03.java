public class Typeconversion_03 {
    public static void main(String[] args) {

        float num2=5.45f;
        int num3=(int)num2;
        System.out.println(num2);
        System.out.println(num3);

        int myInt=(int)5.45f;//explicit type conversion
        System.out.println(myInt);


    }

}
