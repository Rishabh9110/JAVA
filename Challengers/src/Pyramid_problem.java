// print all pyramid star pattern using single print statement

public class Pyramid_problem {
    public static void main(String[] args) {
        System.out.println("*\n* *\n* * *\n* * * *\n* * * * *");
        System.out.println();
        System.out.println("* * * * *\n* * * *\n* * *\n* *\n*");
        System.out.println();
        System.out.println("        *\n      * *\n    * * *\n  * * * *\n* * * * *");

    }
}